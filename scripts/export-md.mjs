// 生成 digests/：可直接在 GitHub 上阅读的纯 Markdown 导出（自动生成，勿手改）。
// 用法：npm run export:md
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const POSTS = path.join(ROOT, 'src/content/posts');
const ARTS = path.join(ROOT, 'src/content/articles');
const OUT = path.join(ROOT, 'digests');
const SITE = 'https://naijoug.github.io/dailyai';
const TYPE = { 'x-ai': 'AI 热点 · X', tech: '科技速递 · Tech' };
// 站内维护说明（信息源增删等），不导出
const PRIVATE = [/^(本次|新增|移除|删除)?信息源[:：]/, /list[_ ]?id/i, /lists\/\d+/i, /(api[_-]?key|secret|token)\s*[:=]/i, /^<!--/];

function parse(file) {
  const raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const fm = {};
  if (m) for (const line of m[1].split('\n')) {
    const k = line.match(/^([A-Za-z_]+):\s*(.*)$/);
    if (!k) continue;
    let v = k[2].trim();
    try { v = JSON.parse(v); } catch { v = v.replace(/^["']|["']$/g, ''); }
    fm[k[1]] = v;
  }
  return { fm, body: m ? m[2] : raw };
}

function clean(body) {
  return body.split('\n')
    .filter((l) => !PRIVATE.some((re) => re.test(l.trim())))
    .map((l) => l.replace(/\s*\[(A|AI):[^\]]*\]/g, '').replace(/<\/?BL[^>]*>/g, '').replace(/^> \[(zh|en)\] ?/, '> **[$1]** '))
    .join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

// 第 n 个列表条目后追加全文链接（序号与 rehype-items 一致：正文中按出现顺序全局递增）
function linkArticles(body, articles, rel) {
  const map = {};
  for (const t of articles || []) { const [i, id] = String(t).split(':'); (map[i] ||= []).push(id); }
  let n = 0;
  return body.split('\n').map((l) => {
    if (!/^\d+\.\s/.test(l)) return l;
    n++;
    const ids = map[n];
    return ids ? l + ids.map((id) => ` · 全文 Full text: [site](${SITE}/article/${id}/) / [md](${rel}articles/${id}.md)`).join('') : l;
  }).join('\n');
}

const shift = (s, by = 1) => s.replace(/^(#{1,5}) /gm, (_, h) => '#'.repeat(h.length + by) + ' ');
const write = (rel, s) => { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s.trim() + '\n'); };
const note = '<!-- Auto-generated by scripts/export-md.mjs — do not edit by hand. -->\n';

fs.rmSync(OUT, { recursive: true, force: true });

const posts = fs.readdirSync(POSTS).filter((f) => /^(x-ai|tech)-\d{4}-\d\d-\d\d-\d{4}\.md$/.test(f)).map((f) => {
  const slug = f.replace(/\.md$/, '');
  const [, type, day, hm] = slug.match(/^(x-ai|tech)-(\d{4}-\d\d-\d\d)-(\d{4})$/);
  const { fm, body } = parse(path.join(POSTS, f));
  return { slug, type, day, time: `${hm.slice(0, 2)}:${hm.slice(2)}`, fm, body };
}).sort((a, b) => (a.day + a.time + a.type).localeCompare(b.day + b.time + b.type));

const meta = (p) => [`- 时间 Time: ${p.day} ${p.time} (UTC+8)`, p.fm.coverage && `- 窗口 Window: ${p.fm.coverage}`, p.fm.tags?.length && `- 标签 Tags: ${p.fm.tags.join(', ')}`].filter(Boolean).join('\n');

const days = {};
for (const p of posts) {
  const [y, mo] = p.day.split('-');
  write(`${y}/${mo}/${p.slug}.md`, `${note}# ${p.fm.title || p.slug}\n\n${meta(p)}\n- 网页 Web: [${SITE}/day/${p.day}/#${p.slug}](${SITE}/day/${p.day}/#${p.slug}) · 当天 Day: [${p.day}](${p.day}.md)\n\n${linkArticles(clean(p.body), p.fm.articles, '../../')}\n`);
  (days[p.day] ||= []).push(p);
}
const dayList = Object.keys(days).sort().reverse();
for (const d of dayList) {
  const [y, mo] = d.split('-'); const ps = days[d];
  const sum = ps.filter((p) => p.fm.daySummary).at(-1);
  let s = `${note}# Daily AI · ${d}\n\n- ${ps.length} 期 issues (UTC+8): ${ps.map((p) => `[${p.time} ${TYPE[p.type]}](${p.slug}.md)`).join(' · ')}\n- 网页 Web: [${SITE}/day/${d}/](${SITE}/day/${d}/)\n`;
  if (sum) s += `\n${sum.fm.daySummary}\n${sum.fm.daySummaryEn ? `\n> ${sum.fm.daySummaryEn}\n` : ''}`;
  for (const p of ps) s += `\n## ${p.time} · ${TYPE[p.type]}\n\n${meta(p)}\n\n${shift(linkArticles(clean(p.body), p.fm.articles, '../../'), 1)}\n`;
  write(`${y}/${mo}/${d}.md`, s);
}

const arts = fs.existsSync(ARTS) ? fs.readdirSync(ARTS).filter((f) => f.endsWith('.md')).map((f) => {
  const id = f.replace(/\.md$/, ''); const { fm, body } = parse(path.join(ARTS, f)); return { id, fm, body };
}).sort((a, b) => String(b.fm.day).localeCompare(String(a.fm.day))) : [];
for (const a of arts) {
  const [y, mo] = String(a.fm.day).split('-');
  const by = a.fm.author + (a.fm.handle ? ` (@${a.fm.handle})` : '');
  write(`articles/${a.id}.md`, `${note}# ${a.fm.title}\n\n${a.fm.title_tr ? `> ${a.fm.title_tr}\n\n` : ''}- 作者 Author: ${by}\n- 原文 Source: ${a.fm.source_url}\n- 发布 Published: ${String(a.fm.published).slice(0, 10)}\n- 来自 From: [${a.fm.day} digest](../${y}/${mo}/${a.fm.day}.md) · 网页 Web: [${SITE}/article/${a.id}/](${SITE}/article/${a.id}/)\n\n> 版权归原作者所有，译文仅为阅读方便。All rights belong to the original author.\n\n${shift(clean(a.body), 1)}\n`);
}

let idx = `${note}# Daily AI · Markdown 导出\n\n每日 AI 热点（X）与科技速递的纯 Markdown 版本，由 \`scripts/export-md.mjs\` 自动生成，请勿手动编辑。\nPlain-Markdown export of the daily digests, auto-generated — do not edit by hand. Website: ${SITE}/\n\n## 每日 Days\n\n`;
for (const d of dayList) { const [y, mo] = d.split('-'); idx += `- [${d}](${y}/${mo}/${d}.md) — ${days[d].slice().reverse().map((p) => `[${p.time} ${p.type === 'tech' ? 'Tech' : 'X'}](${y}/${mo}/${p.slug}.md)`).join(' · ')}\n`; }
idx += `\n## 全文文章 Articles\n\n` + (arts.map((a) => `- [${a.fm.title}](articles/${a.id}.md) — ${a.fm.author} · ${a.fm.day}`).join('\n') || '_none_') + '\n';
write('README.md', idx);
console.log(`export-md: ${posts.length} posts, ${dayList.length} days, ${arts.length} articles → digests/`);
