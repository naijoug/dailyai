// 生成 daily/：可直接在 GitHub 上阅读的纯 Markdown 导出（自动生成，勿手改）。
// 用法：npm run export:md
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const POSTS = path.join(ROOT, 'src/content/posts');
const ARTS = path.join(ROOT, 'src/content/articles');
const IVS = path.join(ROOT, 'src/content/interviews');
const OUT = path.join(ROOT, 'daily');
const SITE = 'https://naijoug.github.io/dailyai';
const TYPE = { 'x-ai': 'AI 热点 · X', tech: '科技速递 · Tech' };
// 站内维护说明（信息源增删等），不导出
const PRIVATE = [/^(本次|新增|移除|删除)?信息源[:：]/, /list[_ ]?id/i, /lists\/\d+/i, /(api[_-]?key|secret|token)\s*[:=]/i, /^<!--/];

function parse(file) {
  const raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const fm = {};
  if (m) for (const line of m[1].split('\n')) {
    const k = line.match(/^([A-Za-z_]+):\s*(.*)$/);
    if (!k) continue;
    let v = k[2].trim();
    try { v = JSON.parse(v); } catch { v = v.replace(/^["']|["']$/g, ''); }
    fm[k[1]] = v;
  }
  return { fm, body: m ? m[2] : raw };
}

function clean(body) {
  return body.split('\n')
    .filter((l) => !PRIVATE.some((re) => re.test(l.trim())))
    .map((l) => l.replace(/\s*\[(A|AI):[^\]]*\]/g, '').replace(/<\/?BL[^>]*>/g, '').replace(/^> \[(zh|en)\] ?/, '> **[$1]** '))
    .join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

const shift = (s, by = 1) => s.replace(/^(#{1,5}) /gm, (_, h) => '#'.repeat(h.length + by) + ' ');
const write = (rel, s) => { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s.trim() + '\n'); };
const note = '<!-- Auto-generated by scripts/export-md.mjs — do not edit by hand. -->\n';

fs.rmSync(OUT, { recursive: true, force: true });

const posts = fs.readdirSync(POSTS).filter((f) => /^(x-ai|tech)-\d{4}-\d\d-\d\d-\d{4}\.md$/.test(f)).map((f) => {
  const slug = f.replace(/\.md$/, '');
  const [, type, day, hm] = slug.match(/^(x-ai|tech)-(\d{4}-\d\d-\d\d)-(\d{4})$/);
  const { fm, body } = parse(path.join(POSTS, f));
  return { slug, type, day, time: `${hm.slice(0, 2)}:${hm.slice(2)}`, fm, body };
}).sort((a, b) => (a.day + a.time + a.type).localeCompare(b.day + b.time + b.type));

const PRODS = path.join(ROOT, 'src/content/products');
const newByDay = {};
if (fs.existsSync(PRODS)) fs.readdirSync(PRODS).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(fs.readFileSync(path.join(PRODS, f), 'utf8')))
  .sort((a, b) => (b.score || 0) - (a.score || 0)).forEach((p) => (newByDay[p.firstSeen] ||= []).push(p.name));

const WD = ['星期日', '星期一', '星期二', '星期三', '星期四', '星期五', '星期六'];
const wd = (d) => WD[new Date(`${d}T12:00:00+08:00`).getUTCDay()];
const isItem = (l) => /^(\d+\.|[-*])\s/.test(l);
const nItems = (ps) => ps.reduce((n, p) => n + p.body.split('\n').filter(isItem).length, 0);
const LINK_RE = /\[([^\]]*)\]\((https?:[^)\s]+)\)|(https?:\/\/[^\s)）｜|]+)/g;
const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ''); } catch { return 'link'; } };
const anchor = (p) => `${p.type === 'tech' ? 'tech' : 'x'}-${p.time.replace(':', '')}`;

// 紧凑条目：中文为主（英文源取 [zh] 译文），去掉译文行，保留原链接 + 评分 + 全文链接
function compact(p) {
  const arts = {};
  for (const t of p.fm.articles || []) { const [i, id] = String(t).split(':'); (arts[i] ||= []).push(id); }
  const lines = clean(p.body).split('\n'); const out = []; let n = 0;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^> /.test(l)) continue;
    if (/^#{1,6} /.test(l)) { out.push('', '#' + l, ''); continue; }
    if (!isItem(l)) { if (l.trim()) out.push('', l.trim(), ''); continue; }
    n++;
    const marker = l.match(/^(\d+\.|[-*])\s+/)[0];
    const orig = l.slice(marker.length);
    const zh = (lines[i + 1] || '').match(/^> \*\*\[zh\]\*\* (.*)$/);
    const links = []; let mm; LINK_RE.lastIndex = 0;
    while ((mm = LINK_RE.exec(orig))) links.push(mm[2] ? `[${mm[1]}](${mm[2]})` : `[${host(mm[3])}](${mm[3]})`);
    let text = (zh ? zh[1] : orig).replace(LINK_RE, '').replace(/\s*[|｜]\s*(?=[|｜]|$)/g, '').replace(/[\s|｜]+$/, '').trim();
    const sc = (p.fm.scores || [])[n - 1];
    const full = (arts[n] || []).map((id) => `📄 全文 [网页](${SITE}/article/${id}/) / [md](../../articles/${id}.md)`);
    out.push(`${marker}${text}${links.length ? ' ' + links.join(' · ') : ''}${sc ? ` ⭐${sc}` : ''}${full.length ? ' · ' + full.join(' · ') : ''}`);
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

const bjDay = (v) => { const d = new Date(/^\d{4}-\d\d-\d\d$/.test(String(v)) ? `${v}T12:00:00+08:00` : v); return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d); };
// 访谈与播客（docs/interviews.md）：只导出摘要要点与少量引用 + 原文链接
const ivs = fs.existsSync(IVS) ? fs.readdirSync(IVS).filter((f) => f.endsWith('.md')).map((f) => {
  const id = f.replace(/\.md$/, ''); const { fm, body } = parse(path.join(IVS, f)); return { id, fm, body, day: bjDay(fm.date) };
}).sort((a, b) => String(b.fm.date).localeCompare(String(a.fm.date))) : [];
const ivByDay = {};
for (const iv of ivs) (ivByDay[iv.day] ||= []).push(iv);
const KIND = { podcast: '播客', article: '访谈' };
// 中文为主：英文源取 [zh] 译文
function ivZh(iv) {
  const zh = (o, tr) => (iv.fm.lang === 'zh' ? o : tr || o);
  const lines = iv.body.replace(/\r\n/g, '\n').split('\n'); const out = [];
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^#{1,6} /.test(l)) { out.push(`${out.length ? '\n' : ''}**${l.replace(/^#+\s*/, '')}**\n`); continue; }
    if (!/^[-*]\s/.test(l)) continue;
    const m = (lines[i + 1] || '').match(/^\s*>\s*\[(zh|en)\]\s*(.*)$/);
    out.push(`- ${iv.fm.lang === 'zh' || !m || m[1] !== 'zh' ? l.replace(/^[-*]\s+/, '') : m[2]}`);
  }
  const head = `### ${KIND[iv.fm.kind] || '访谈'} · ${iv.fm.show}：${zh(iv.fm.title, iv.fm.title_tr)}`;
  const meta = [iv.fm.guests?.length ? `嘉宾：${iv.fm.guests.join('、')}` : '', iv.fm.duration ? `时长 ${iv.fm.duration}` : '', iv.fm.score ? `⭐${iv.fm.score}` : ''].filter(Boolean).join(' · ');
  return `${head}\n\n${zh(iv.fm.summary, iv.fm.summary_tr)}\n\n${meta ? meta + '\n\n' : ''}${out.join('\n')}\n\n[原文](${iv.fm.url}) · [网页](${SITE}/interview/${iv.id}/)\n`;
}
const days = {};
for (const p of posts) (days[p.day] ||= []).push(p);
for (const d of Object.keys(ivByDay)) days[d] ||= [];
const dayList = Object.keys(days).sort().reverse();
const dpath = (d) => `${d.slice(0, 4)}/${d.slice(5, 7)}/${d}.md`;
const info = {};
for (const d of dayList) {
  const ps = days[d];
  const withSum = [...ps].reverse().find((p) => p.fm.daySummary);
  const lastHead = (arr) => { const l = arr.at(-1)?.body.split('\n').find(isItem); return l ? l.replace(/^(\d+\.|[-*])\s+/, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/https?:\/\/\S+/g, '').replace(/[*_`]/g, '').split(/[：:（(。]/)[0].trim().slice(0, 60) : null; };
  const xai = ps.filter((p) => p.type === 'x-ai'), tech = ps.filter((p) => p.type === 'tech');
  const iv0 = (ivByDay[d] || [])[0];
  info[d] = { summary: withSum?.fm.daySummary || [lastHead(xai), lastHead(tech)].filter(Boolean).join('；') || (iv0 ? `${iv0.fm.show}：${iv0.fm.lang === 'zh' ? iv0.fm.summary : iv0.fm.summary_tr || iv0.fm.summary}` : ''), ai: nItems(xai), tech: nItems(tech), iv: (ivByDay[d] || []).length, top: ps.flatMap((p) => p.fm.scores || []).filter((x) => x >= 4).length };
}
const counts = (d) => { const x = info[d]; return [x.ai && `AI Hot ${x.ai}`, x.tech && `Tech ${x.tech}`, x.iv && `访谈/播客 ${x.iv}`, x.top && `⭐ ${x.top} 条高分`].filter(Boolean).join(' · '); };

dayList.forEach((d, i) => {
  const ps = days[d]; const newer = dayList[i - 1], older = dayList[i + 1];
  const rel = (o) => `../../${dpath(o)}`;
  const nav = [older && `← [${older}](${rel(older)})`, `[📅 索引](../../README.md)`, newer && `[${newer}](${rel(newer)}) →`].filter(Boolean).join(' · ');
  let s = `${note}# Daily AI · ${d} · ${wd(d)}\n\n${nav}\n\n${info[d].summary}\n\n${counts(d)} · [网页版](${SITE}/day/${d}/)\n\n**目录：** ${[...ps.map((p) => `[${p.type === 'tech' ? 'Tech' : 'X'} ${p.time}](#${anchor(p)})`), ...(ivByDay[d] ? ['[访谈与播客](#interviews)'] : [])].join(' · ')}\n`;
  for (const p of ps) s += `\n<a id="${anchor(p)}"></a>\n\n## ${p.type === 'tech' ? 'Tech' : 'X'} ${p.time} · ${TYPE[p.type]}\n\n${p.fm.coverage ? `_${p.fm.coverage}_\n\n` : ''}${compact(p)}\n`;
  if (ivByDay[d]) s += `\n<a id="interviews"></a>\n\n## 访谈与播客 · Interviews & Podcasts\n\n> 仅摘要与少量原话引用，版权归原发布方，完整内容请看原文。\n\n${ivByDay[d].map(ivZh).join('\n')}`;
  s += `\n---\n\n${nav}\n`;
  write(dpath(d), s);
});

const arts = fs.existsSync(ARTS) ? fs.readdirSync(ARTS).filter((f) => f.endsWith('.md')).map((f) => {
  const id = f.replace(/\.md$/, ''); const { fm, body } = parse(path.join(ARTS, f)); return { id, fm, body };
}).sort((a, b) => String(b.fm.day).localeCompare(String(a.fm.day))) : [];
for (const a of arts) {
  const [y, mo] = String(a.fm.day).split('-');
  const by = a.fm.author + (a.fm.handle ? ` (@${a.fm.handle})` : '');
  write(`articles/${a.id}.md`, `${note}# ${a.fm.title}\n\n${a.fm.title_tr ? `> ${a.fm.title_tr}\n\n` : ''}- 作者 Author: ${by}\n- 原文 Source: ${a.fm.source_url}\n- 发布 Published: ${String(a.fm.published).slice(0, 10)}\n- 来自 From: [${a.fm.day} digest](../${y}/${mo}/${a.fm.day}.md) · 网页 Web: [${SITE}/article/${a.id}/](${SITE}/article/${a.id}/)\n\n> 版权归原作者所有，译文仅为阅读方便。All rights belong to the original author.\n\n${shift(clean(a.body), 1)}\n`);
}

let idx = `${note}# 📰 Daily AI · Markdown 每日索引\n\n每日 AI 热点（X）与科技速递，按天汇总。由 \`scripts/export-md.mjs\` 自动生成，请勿手动编辑。网页版：${SITE}/\n`;
let curM = '';
for (const d of dayList) {
  if (d.slice(0, 7) !== curM) { curM = d.slice(0, 7); idx += `\n## ${curM.slice(0, 4)} 年 ${+curM.slice(5)} 月\n`; }
  const np = newByDay[d] || [];
  idx += `\n### ${d} · ${wd(d)}\n\n${info[d].summary}\n\n`;
  if (np.length) idx += `🆕 今日新品：${np.slice(0, 3).join('、')}${np.length > 3 ? ` +${np.length - 3}` : ''}\n\n`;
  if (ivByDay[d]) idx += `🎙 访谈与播客：${ivByDay[d].map((iv) => iv.fm.show).join('、')}\n\n`;
  idx += `${counts(d)}\n\n[→ 查看当天详情](${dpath(d)})\n`;
}
idx += `\n## 访谈与播客\n\n` + (ivs.map((iv) => `- [${iv.fm.show}：${iv.fm.lang === 'zh' ? iv.fm.title : iv.fm.title_tr || iv.fm.title}](${dpath(iv.day)}#interviews) — ${KIND[iv.fm.kind] || '访谈'} · ${iv.day} · [原文](${iv.fm.url})`).join('\n') || '_暂无_') + '\n';
idx += `\n## 全文文章\n\n` + (arts.map((a) => `- [${a.fm.title}](articles/${a.id}.md) — ${a.fm.author} · ${a.fm.day}`).join('\n') || '_暂无_') + '\n';
write('README.md', idx);
console.log(`export-md: ${posts.length} posts, ${ivs.length} interviews, ${dayList.length} days, ${arts.length} articles → daily/`);
